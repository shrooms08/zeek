/**
 * Ink art for the engine's share cards, generated from the app's own art
 * kit (apps/web/src/art) so the PNG matches the app exactly:
 *   config/share/art-win.svg    Zeb holding the open gold chest (prove-a-win)
 *   config/share/art-round.svg  the open gold chest (round result)
 *   config/share/lockup.svg     the Zeek lockup at the configured "eek" slant
 * Each is an SVG fragment (defs + group) the engine embeds with include_str!.
 * Run: node scripts/share-art.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as esbuild from "../node_modules/.pnpm/esbuild@0.28.2/node_modules/esbuild/lib/main.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const art = path.join(root, "apps/web/src/art");
const outfile = path.join(tmpdir(), `zeek-share-art-${process.pid}.mjs`);
await esbuild.build({
  stdin: {
    contents: `export { defs } from "./ink"; export { chest, zeb } from "./props"; export { EEK_SLANT, eekMarkup, zMarkMarkup, LOGO_VIEWBOX } from "./logoGeometry";`,
    resolveDir: art,
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  outfile,
  logLevel: "error",
});
const kit = await import(pathToFileURL(outfile).href);
const p = "sa_";
const dir = path.join(root, "config/share");
mkdirSync(dir, { recursive: true });
const banner = "<!-- Generated by scripts/share-art.mjs from apps/web/src/art; do not edit. -->\n";
writeFileSync(
  path.join(dir, "art-win.svg"),
  `${banner}<defs>${kit.defs(p)}</defs>${kit.zeb("chest", p, true)}\n`,
);
writeFileSync(
  path.join(dir, "art-round.svg"),
  `${banner}<defs>${kit.defs(p)}</defs>${kit.chest(true, true)}\n`,
);
writeFileSync(
  path.join(dir, "lockup.svg"),
  `${banner}${kit.zMarkMarkup("#FFFFFF", "#0D0D0D")}${kit.eekMarkup("#0D0D0D", kit.EEK_SLANT).replace(/font-family="[^"]*"/, 'font-family="Archivo Black"')}\n`,
);
console.log("share art written", kit.LOGO_VIEWBOX);
