#!/usr/bin/env node
// Writes docs/third-party.md: the third-party code and assets Zeek uses and
// their licenses, from `cargo metadata` (Rust crates reachable through
// normal and build dependencies) and `pnpm licenses list --prod` (the web
// app's production packages).
//
//   node scripts/third-party.mjs

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

const meta = JSON.parse(run("cargo", ["metadata", "--format-version", "1", "--locked"]));
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const members = new Set(meta.workspace_members);
const reach = new Set();
const stack = [...members];
while (stack.length > 0) {
  const id = stack.pop();
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.every((k) => k.kind === "dev")) continue;
    if (!reach.has(dep.pkg)) {
      reach.add(dep.pkg);
      stack.push(dep.pkg);
    }
  }
}
const crates = [...reach]
  .filter((id) => !members.has(id) && byId.get(id)?.source !== null)
  .map((id) => byId.get(id))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const count = (items, key) => {
  const m = new Map();
  for (const it of items) m.set(key(it), (m.get(key(it)) ?? 0) + 1);
  return [...m.entries()].sort((a, b) => b[1] - a[1]);
};

const js = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"]));
const jsPackages = Object.entries(js)
  .flatMap(([license, pkgs]) => pkgs.map((p) => ({ name: p.name, versions: p.versions, license })))
  .sort((a, b) => a.name.localeCompare(b.name));

const md = `# Third-party code and assets

Generated by \`node scripts/third-party.mjs\`. Everything in this repository
not listed here was written for Zeek in this repository's history. Zeek
itself is dual-licensed MIT OR Apache-2.0 (\`LICENSE-MIT\`,
\`LICENSE-APACHE\`).

## Vendored source

| Path | What | License |
| --- | --- | --- |
| \`vendor/zcash_protocol/\` | The published \`zcash_protocol\` 0.10.6 crate (Electric Coin Company and the Zcash developers), with three edits that give testnet NU7 its activation height and branch ID; see \`vendor/zcash_protocol/ZEEK-PATCH.md\`. | MIT OR Apache-2.0 |

## Design files

\`design/mono/\` holds Zeek's own design system (Zeek Mono: the field, the
dig flow, the reveal, motion), made for this project; the web app's art kit
(\`apps/web/src/art/\`) is a typed port of its generator.

## Bundled assets

| Path | What | License |
| --- | --- | --- |
| \`config/share/fonts/ArchivoBlack-Regular.ttf\` | Archivo Black (Omnibus-Type), for the share cards | SIL Open Font License 1.1 (\`OFL-ArchivoBlack.txt\`) |
| \`config/share/fonts/JetBrainsMono-wght.ttf\` | JetBrains Mono, for the share cards | SIL Open Font License 1.1 (\`OFL-JetBrainsMono.txt\`) |
| \`@fontsource-variable/archivo\`, \`@fontsource/archivo-black\`, \`@fontsource/jetbrains-mono\` | The same fonts, self-hosted by the web app | SIL Open Font License 1.1 |

## Rust crates

${crates.length} crates from crates.io (normal and build dependencies of the
workspace; test-only crates excluded), plus the vendored one above.

| License | Crates |
| --- | --- |
${count(crates, (c) => c.license ?? "(none)")
  .map(([l, n]) => `| ${l} | ${n} |`)
  .join("\n")}

<details><summary>Every crate</summary>

| Crate | Version | License |
| --- | --- | --- |
${crates.map((c) => `| ${c.name} | ${c.version} | ${c.license ?? "(none)"} |`).join("\n")}

</details>

## JavaScript packages (web app, production)

${jsPackages.length} packages.

| License | Packages |
| --- | --- |
${count(jsPackages, (p) => p.license)
  .map(([l, n]) => `| ${l} | ${n} |`)
  .join("\n")}

| Package | Versions | License |
| --- | --- | --- |
${jsPackages.map((p) => `| ${p.name} | ${p.versions.join(", ")} | ${p.license} |`).join("\n")}
`;
writeFileSync(join(root, "docs/third-party.md"), md);
console.log(`wrote docs/third-party.md (${crates.length} crates, ${jsPackages.length} packages)`);
